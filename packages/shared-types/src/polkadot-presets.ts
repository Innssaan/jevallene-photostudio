function svgDataUri(svg: string): string {
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg.trim())}`;
}

/**
 * Generates a seamless, aspect-ratio-safe SVG polka-dot backdrop.
 * Uses preserveAspectRatio="xMidYMid slice" so dots remain circular
 * across 1:1, 4:5, 9:16, and 16:9 exports.
 */
function buildPolkadotBackdrop(
  bgColor: string,
  dotColor1: string,
  dotColor2?: string,
  dotRadius = 18,
  spacing = 96
): string {
  const c2 = dotColor2 ?? dotColor1;
  const r2 = dotColor2 ? Math.max(8, Math.round(dotRadius * 0.85)) : dotRadius;
  const half = spacing / 2;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1080 1920" preserveAspectRatio="xMidYMid slice">
    <defs>
      <pattern id="dots" width="${spacing}" height="${spacing}" patternUnits="userSpaceOnUse">
        <circle cx="${Math.round(spacing * 0.25)}" cy="${Math.round(spacing * 0.25)}" r="${dotRadius}" fill="${dotColor1}" opacity="0.92"/>
        <circle cx="${Math.round(spacing * 0.25 + half)}" cy="${Math.round(spacing * 0.25 + half)}" r="${r2}" fill="${c2}" opacity="0.92"/>
      </pattern>
    </defs>
    <rect width="1080" height="1920" fill="${bgColor}"/>
    <rect width="1080" height="1920" fill="url(#dots)"/>
  </svg>`;
  return svgDataUri(svg);
}

