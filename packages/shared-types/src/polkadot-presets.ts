function buildSlotFrames(
  slots: PhotoSlot[],
  fillColor: string,
  strokeColor: string,
  strokeWidth = 6,
  pad = 12
): TemplateLayer[] {
  return slots.map((s, idx) => ({
    id: `frame-${idx + 1}`,
    type: "shape" as const,
    shapeKind: "rect" as const,
    x: s.x - pad,
    y: s.y - pad,
    width: s.width + pad * 2,
    height: s.height + pad * 2,
    borderRadius: (s.borderRadius ?? 16) + 6,
    tintColor: fillColor,
    strokeColor,
    strokeWidth,
    zIndex: -1,
    visible: true,
  }));
}

function buildBackdropLayer(id: string, svgUri: string): TemplateLayer {
  return {
    id,
    type: "sticker",
    assetId: svgUri,
    x: 0,
    y: 0,
    width: 1080,
    height: 1920,
    zIndex: -2,
    visible: true,
  };
}

