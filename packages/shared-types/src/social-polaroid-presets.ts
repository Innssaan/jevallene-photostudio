type SocialLayout =
  | "polaroid-single"
  | "polaroid-duo"
  | "polaroid-3"
  | "story-3"
  | "story-polaroid-2"
  | "story-grid-4"
  | "feed-45-grid"
  | "feed-45-hero"
  | "feed-11-grid"
  | "feed-34-grid"
  | "feed-34-hero";

interface SocialSpec {
  id: string;
  category: TemplateCategory;
  title: string;
  descId: string;
  descEn: string;
  theme: TemplateTheme;
  layout: SocialLayout;
  bg: string;
  isGradient?: boolean;
  contrastMode: "light" | "dark";
  titleColor: string;
  kickerColor: string;
  subColor: string;
  borderColor: string;
  titleFont: string;
  bodyFont: string;
  kicker: string;
  headline: string;
  footerTitle: string;
  footerSub: string;
  filter: FilterPreset;
  stickers: string[];
  doodleDense?: boolean;
  wmStyle?: WatermarkStyle;
  wmPlacement?: WatermarkPlacement;
}

const makeRect = (
  id: string,
  x: number,
  y: number,
  w: number,
  h: number,
  fill: string,
  z: number,
  extra: Partial<TemplateLayer> = {}
): TemplateLayer =>
  ({
    id,
    type: "shape",
    shapeKind: "rect",
    x,
    y,
    width: w,
    height: h,
    visible: true,
    tintColor: fill,
    zIndex: z,
    ...extra,
  }) as TemplateLayer;

const makeSticker = (
  id: string,
  assetId: string,
  x: number,
  y: number,
  w: number,
  h: number,
  rotation = 0,
  z = 6
): TemplateLayer => ({
  id,
  type: "sticker",
  assetId,
  x,
  y,
  width: w,
  height: h,
  rotation,
  opacity: 1,
  visible: true,
  zIndex: z,
});

const makeText = (
  id: string,
  x: number,
  y: number,
  w: number,
  h: number,
  content: string,
  fontFamily: string,
  fontSize: number,
  color: string,
  extra: Partial<TemplateLayer> = {}
): TemplateLayer =>
  ({
    id,
    type: "text",
    x,
    y,
    width: w,
    height: h,
    visible: true,
    content,
    fontFamily,
    fontSize,
    color,
    align: "center",
    zIndex: 7,
    ...extra,
  }) as TemplateLayer;

function buildSocialTemplate(spec: SocialSpec): TemplatePreset {
  const slots: PhotoSlot[] = [];
  const layers: TemplateLayer[] = [];

  let width = 1080;
  let height = 1920;
  let aspectRatio: AspectRatioPreset = "9:16";

  const addPolaroidCard = (
    idx: number,
    px: number,
    py: number,
    pw: number,
    ph: number,
    rot = 0
  ) => {
    const pad = Math.round(pw * 0.065);
    const bottomPad = Math.round(pw * 0.22);
    layers.push(
      makeRect(`pcard-${idx}`, px, py, pw, ph, "#ffffff", -1, {
        rotation: rot,
        borderRadius: 6,
        strokeColor: spec.borderColor,
        strokeWidth: 2,
      })
    );
    slots.push({
      id: `slot-${idx + 1}`,
      index: idx,
      x: px + pad,
      y: py + pad,
      width: pw - pad * 2,
      height: ph - pad - bottomPad,
      rotation: rot,
      borderRadius: 2,
      filter: spec.filter,
    });
  };

  const addFramedSlot = (
    idx: number,
    x: number,
    y: number,
    w: number,
    h: number,
    radius = 12,
    rot = 0
  ) => {
    slots.push({
      id: `slot-${idx + 1}`,
      index: idx,
      x,
      y,
      width: w,
      height: h,
      rotation: rot,
      borderRadius: radius,
      filter: spec.filter,
    });
    layers.push(
      makeRect(`frm-${idx}`, x - 3, y - 3, w + 6, h + 6, "transparent", -1, {
        rotation: rot,
        borderRadius: radius + 3,
        strokeColor: spec.borderColor,
        strokeWidth: 3,
      })
    );
  };

  if (spec.layout === "polaroid-single") {
    width = 800;
    height = 1000;
    aspectRatio = "4:5";
    addPolaroidCard(0, 68, 66, 664, 640, 0);
    addPolaroidCard(1, 520, 572, 224, 280, 5);
    layers.push(
      makeText("title", 76, 742, 440, 56, spec.headline, spec.titleFont, 40, spec.titleColor),
      makeText("sub", 76, 804, 440, 26, spec.footerSub, spec.bodyFont, 14, spec.subColor, { letterSpacing: 2.2 }),
      makeSticker("s1", spec.stickers[0], 34, 42, 82, 82, -12, 6),
      makeSticker("s2", spec.stickers[1 % spec.stickers.length], 684, 42, 82, 82, 12, 6),
      makeSticker("s3", spec.stickers[2 % spec.stickers.length], 34, 780, 84, 84, -8, 6)
    );
  } else if (spec.layout === "polaroid-duo") {
    width = 800;
    height = 1200;
    aspectRatio = "2:3";
    addPolaroidCard(0, 80, 148, 440, 490, -4);
    addPolaroidCard(1, 280, 540, 440, 490, 4);
    layers.push(
      makeText("kicker", 100, 42, 600, 24, spec.kicker, spec.bodyFont, 14, spec.kickerColor, { letterSpacing: 3 }),
      makeText("title", 100, 72, 600, 56, spec.headline, spec.titleFont, 44, spec.titleColor),
      makeText("ft", 80, 1068, 460, 44, spec.footerTitle, spec.titleFont, 32, spec.titleColor),
      makeSticker("s1", spec.stickers[0], 560, 160, 110, 110, 12, 6),
      makeSticker("s2", spec.stickers[1 % spec.stickers.length], 58, 690, 110, 110, -12, 6),
      makeSticker("s3", spec.stickers[2 % spec.stickers.length], 640, 930, 96, 96, 10, 6)
    );
  } else if (spec.layout === "polaroid-3") {
    width = 800;
    height = 1200;
    aspectRatio = "2:3";
    addPolaroidCard(0, 64, 152, 340, 410, -3);
    addPolaroidCard(1, 396, 168, 340, 410, 3);
    addPolaroidCard(2, 224, 594, 352, 420, -1);
    layers.push(
      makeText("kicker", 100, 40, 600, 24, spec.kicker, spec.bodyFont, 14, spec.kickerColor, { letterSpacing: 3 }),
      makeText("title", 100, 70, 600, 56, spec.headline, spec.titleFont, 44, spec.titleColor),
      makeText("ft", 80, 1054, 460, 44, spec.footerTitle, spec.titleFont, 32, spec.titleColor),
      makeSticker("s1", spec.stickers[0], 34, 620, 96, 96, -12, 6),
      makeSticker("s2", spec.stickers[1 % spec.stickers.length], 658, 636, 96, 96, 14, 6),
      makeSticker("s3", spec.stickers[2 % spec.stickers.length], 354, 536, 86, 86, 6, 6)
    );
  } else if (spec.layout === "story-3") {
    width = 1080;
    height = 1920;
    aspectRatio = "9:16";
    [290, 760, 1230].forEach((y, i) => addFramedSlot(i, 120, y, 840, 430, 18));
    layers.push(
      makeText("kicker", 120, 104, 840, 30, spec.kicker, spec.bodyFont, 20, spec.kickerColor, { letterSpacing: 4 }),
      makeText("title", 100, 148, 880, 96, spec.headline, spec.titleFont, 68, spec.titleColor),
      makeText("ft", 120, 1700, 840, 64, spec.footerTitle, spec.titleFont, 46, spec.titleColor),
      makeText("sub", 120, 1774, 840, 30, spec.footerSub, spec.bodyFont, 18, spec.subColor, { letterSpacing: 3 })
    );
    const anchors: Array<[number, number, number, number]> = [
      [48, 86, 106, -12],
      [924, 92, 106, 12],
      [54, 696, 98, -14],
      [928, 700, 98, 14],
      [54, 1170, 98, 10],
      [928, 1174, 98, -10],
      [58, 1660, 106, -10],
      [916, 1660, 106, 10],
    ];
    anchors.forEach(([x, y, sz, rot], idx) => {
      if (spec.doodleDense || (spec.theme !== "minimal" && spec.theme !== "korean") || idx < 2) {
        layers.push(makeSticker(`s-${idx}`, spec.stickers[idx % spec.stickers.length], x, y, sz, sz, rot, 6));
      }
    });
  } else if (spec.layout === "story-polaroid-2") {
    width = 1080;
    height = 1920;
    aspectRatio = "9:16";
    addPolaroidCard(0, 130, 290, 820, 660, -3);
    addPolaroidCard(1, 130, 980, 820, 660, 3);
    layers.push(
      makeText("kicker", 120, 104, 840, 30, spec.kicker, spec.bodyFont, 20, spec.kickerColor, { letterSpacing: 4 }),
      makeText("title", 100, 148, 880, 96, spec.headline, spec.titleFont, 68, spec.titleColor),
      makeText("ft", 120, 1696, 840, 64, spec.footerTitle, spec.titleFont, 46, spec.titleColor),
      makeText("sub", 120, 1770, 840, 30, spec.footerSub, spec.bodyFont, 18, spec.subColor, { letterSpacing: 3 }),
      makeSticker("s1", spec.stickers[0], 56, 230, 116, 116, -12, 6),
      makeSticker("s2", spec.stickers[1 % spec.stickers.length], 908, 890, 116, 116, 14, 6),
      makeSticker("s3", spec.stickers[2 % spec.stickers.length], 60, 1560, 116, 116, -10, 6)
    );
  } else if (spec.layout === "story-grid-4") {
    width = 1080;
    height = 1920;
    aspectRatio = "9:16";
    [
      [96, 300],
      [564, 300],
      [96, 980],
      [564, 980],
    ].forEach(([x, y], i) => addFramedSlot(i, x, y, 420, 640, 16));
    layers.push(
      makeText("kicker", 120, 104, 840, 30, spec.kicker, spec.bodyFont, 20, spec.kickerColor, { letterSpacing: 4 }),
      makeText("title", 100, 148, 880, 96, spec.headline, spec.titleFont, 68, spec.titleColor),
      makeText("ft", 120, 1686, 840, 64, spec.footerTitle, spec.titleFont, 46, spec.titleColor),
      makeText("sub", 120, 1762, 840, 30, spec.footerSub, spec.bodyFont, 18, spec.subColor, { letterSpacing: 3 }),
      makeSticker("s1", spec.stickers[0], 48, 92, 104, 104, -12, 6),
      makeSticker("s2", spec.stickers[1 % spec.stickers.length], 928, 92, 104, 104, 12, 6),
      makeSticker("s3", spec.stickers[2 % spec.stickers.length], 484, 906, 112, 112, 8, 6)
    );
  } else if (spec.layout === "feed-45-grid" || spec.layout === "feed-34-grid") {
    width = 1080;
    height = spec.layout === "feed-45-grid" ? 1350 : 1440;
    aspectRatio = spec.layout === "feed-45-grid" ? "4:5" : "3:4";
    const slotH = spec.layout === "feed-45-grid" ? 440 : 480;
    const row2Y = 230 + slotH + 34;
    [
      [88, 230],
      [554, 230],
      [88, row2Y],
      [554, row2Y],
    ].forEach(([x, y], i) => addFramedSlot(i, x, y, 438, slotH, 14));
    const footY = row2Y + slotH + 34;
    layers.push(
      makeText("kicker", 120, 64, 840, 28, spec.kicker, spec.bodyFont, 18, spec.kickerColor, { letterSpacing: 3.5 }),
      makeText("title", 100, 104, 880, 84, spec.headline, spec.titleFont, 60, spec.titleColor),
      makeText("ft", 100, footY, 640, 56, spec.footerTitle, spec.titleFont, 40, spec.titleColor),
      makeText("sub", 100, footY + 62, 640, 26, spec.footerSub, spec.bodyFont, 15, spec.subColor, { letterSpacing: 2.5 }),
      makeSticker("s1", spec.stickers[0], 46, 56, 98, 98, -12, 6),
      makeSticker("s2", spec.stickers[1 % spec.stickers.length], 936, 56, 98, 98, 12, 6),
      makeSticker("s3", spec.stickers[2 % spec.stickers.length], 486, 230 + slotH - 36, 108, 108, 6, 6)
    );
  } else if (spec.layout === "feed-45-hero" || spec.layout === "feed-34-hero") {
    width = 1080;
    height = spec.layout === "feed-45-hero" ? 1350 : 1440;
    aspectRatio = spec.layout === "feed-45-hero" ? "4:5" : "3:4";
    const heroH = spec.layout === "feed-45-hero" ? 540 : 590;
    const subY = 230 + heroH + 30;
    const subH = spec.layout === "feed-45-hero" ? 340 : 380;
    addFramedSlot(0, 88, 230, 904, heroH, 16);
    addFramedSlot(1, 88, subY, 436, subH, 14);
    addFramedSlot(2, 556, subY, 436, subH, 14);
    const footY = subY + subH + 34;
    layers.push(
      makeText("kicker", 120, 64, 840, 28, spec.kicker, spec.bodyFont, 18, spec.kickerColor, { letterSpacing: 3.5 }),
      makeText("title", 100, 104, 880, 84, spec.headline, spec.titleFont, 60, spec.titleColor),
      makeText("ft", 100, footY, 640, 56, spec.footerTitle, spec.titleFont, 40, spec.titleColor),
      makeText("sub", 100, footY + 62, 640, 26, spec.footerSub, spec.bodyFont, 15, spec.subColor, { letterSpacing: 2.5 }),
      makeSticker("s1", spec.stickers[0], 46, 56, 98, 98, -12, 6),
      makeSticker("s2", spec.stickers[1 % spec.stickers.length], 936, 56, 98, 98, 12, 6)
    );
  } else {
    // feed-11-grid (1080x1080 1:1 square)
    width = 1080;
    height = 1080;
    aspectRatio = "1:1";
    [
      [88, 200],
      [554, 200],
      [88, 574],
      [554, 574],
    ].forEach(([x, y], i) => addFramedSlot(i, x, y, 438, 344, 12));
    layers.push(
      makeText("kicker", 120, 52, 840, 26, spec.kicker, spec.bodyFont, 16, spec.kickerColor, { letterSpacing: 3 }),
      makeText("title", 100, 88, 880, 76, spec.headline, spec.titleFont, 54, spec.titleColor),
      makeText("ft", 100, 944, 620, 48, spec.footerTitle, spec.titleFont, 36, spec.titleColor),
      makeText("sub", 100, 998, 620, 24, spec.footerSub, spec.bodyFont, 14, spec.subColor, { letterSpacing: 2.5 }),
      makeSticker("s1", spec.stickers[0], 46, 48, 88, 88, -12, 6),
      makeSticker("s2", spec.stickers[1 % spec.stickers.length], 946, 48, 88, 88, 12, 6),
      makeSticker("s3", spec.stickers[2 % spec.stickers.length], 492, 514, 96, 96, 8, 6)
    );
  }

  return {
    id: spec.id,
    slug: spec.id,
    title_id: spec.title,
    title_en: spec.title,
    description_id: spec.descId,
    description_en: spec.descEn,
    category: spec.category,
    theme: spec.theme,
    is_featured: true,
    is_new: true,
    popularity_score: 95,
    document: {
      schemaVersion: "1.0",
      templateId: spec.id,
      version: 1,
      category: spec.category,
      theme: spec.theme,
      canvas: {
        width,
        height,
        aspectRatio,
        background: {
          type: spec.isGradient ? "gradient" : "solid",
          value: spec.bg,
        },
      },
      slots,
      layers,
      watermark: enforceMandatoryWatermark({
        placement: spec.wmPlacement ?? "bottom-right",
        contrastMode: spec.contrastMode,
        fontFamily: spec.bodyFont,
        style: spec.wmStyle ?? "minimal",
      }),
    },
  };
}

