const rect = (
  id: string,
  x: number,
  y: number,
  w: number,
  h: number,
  fill: string,
  z: number,
  extra: Partial<TemplateLayer> = {}
): TemplateLayer =>
  ({
    id,
    type: "shape",
    shapeKind: "rect",
    x,
    y,
    width: w,
    height: h,
    visible: true,
    tintColor: fill,
    zIndex: z,
    ...extra,
  }) as TemplateLayer;

const stk = (
  id: string,
  assetId: string,
  x: number,
  y: number,
  w: number,
  h: number,
  rotation = 0,
  z = 6
): TemplateLayer => ({
  id,
  type: "sticker",
  assetId,
  x,
  y,
  width: w,
  height: h,
  rotation,
  opacity: 1,
  visible: true,
  zIndex: z,
});

const txt = (
  id: string,
  x: number,
  y: number,
  w: number,
  h: number,
  content: string,
  fontFamily: string,
  fontSize: number,
  color: string,
  extra: Partial<TemplateLayer> = {}
): TemplateLayer =>
  ({
    id,
    type: "text",
    x,
    y,
    width: w,
    height: h,
    visible: true,
    content,
    fontFamily,
    fontSize,
    color,
    align: "center",
    zIndex: 7,
    ...extra,
  }) as TemplateLayer;

const makePreset = (opts: {
  id: string;
  title: string;
  descId: string;
  descEn: string;
  category: TemplateCategory;
  theme: TemplateTheme;
  width: number;
  height: number;
  aspectRatio: AspectRatioPreset;
  bg: string;
  isGradient?: boolean;
  slots: PhotoSlot[];
  layers: TemplateLayer[];
  contrastMode: "light" | "dark";
  wmFont: string;
  wmStyle?: WatermarkStyle;
  wmPlacement?: WatermarkPlacement;
}): TemplatePreset => ({
  id: opts.id,
  slug: opts.id,
  title_id: opts.title,
  title_en: opts.title,
  description_id: opts.descId,
  description_en: opts.descEn,
  category: opts.category,
  theme: opts.theme,
  is_featured: true,
  is_new: true,
  popularity_score: 98,
  document: {
    schemaVersion: "1.0",
    templateId: opts.id,
    version: 1,
    category: opts.category,
    theme: opts.theme,
    canvas: {
      width: opts.width,
      height: opts.height,
      aspectRatio: opts.aspectRatio,
      background: {
        type: opts.isGradient ? "gradient" : "solid",
        value: opts.bg,
      },
    },
    slots: opts.slots,
    layers: opts.layers,
    watermark: enforceMandatoryWatermark({
      placement: opts.wmPlacement ?? "bottom-center",
      contrastMode: opts.contrastMode,
      fontFamily: opts.wmFont,
      style: opts.wmStyle ?? "minimal",
    }),
  },
});

