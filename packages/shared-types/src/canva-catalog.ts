type LayoutKind =
  | "strip-3"
  | "strip-4"
  | "dual-strip-3"
  | "grid-2x2"
  | "hero-3"
  | "landscape-3";

interface CanvaSpec {
  id: string;
  title: string;
  descId: string;
  descEn: string;
  theme: TemplateTheme;
  layout: LayoutKind;
  bg: string;
  isGradient?: boolean;
  contrastMode: "light" | "dark";
  titleColor: string;
  kickerColor: string;
  subColor: string;
  borderColor: string;
  accentColor: string;
  titleFont: string;
  bodyFont: string;
  kicker: string;
  headline: string;
  footerTitle: string;
  footerSub: string;
  filter: FilterPreset;
  stickerTop?: string;
  stickerLeft?: string;
  stickerRight?: string;
  watermarkStyle?: WatermarkStyle;
  watermarkPlacement?: WatermarkPlacement;
  borderRadius?: number;
  popularity?: number;
}

const makeRect = (
  id: string,
  x: number,
  y: number,
  w: number,
  h: number,
  fill: string,
  z: number,
  extra: Partial<TemplateLayer> = {}
): TemplateLayer =>
  ({
    id,
    type: "shape",
    shapeKind: "rect",
    x,
    y,
    width: w,
    height: h,
    visible: true,
    tintColor: fill,
    zIndex: z,
    ...extra,
  }) as TemplateLayer;

const makeSticker = (
  id: string,
  assetId: string,
  x: number,
  y: number,
  w: number,
  h: number,
  rotation = 0,
  z = 6
): TemplateLayer => ({
  id,
  type: "sticker",
  assetId,
  x,
  y,
  width: w,
  height: h,
  rotation,
  opacity: 1,
  visible: true,
  zIndex: z,
});

const makeText = (
  id: string,
  x: number,
  y: number,
  w: number,
  h: number,
  content: string,
  fontFamily: string,
  fontSize: number,
  color: string,
  extra: Partial<TemplateLayer> = {}
): TemplateLayer =>
  ({
    id,
    type: "text",
    x,
    y,
    width: w,
    height: h,
    visible: true,
    content,
    fontFamily,
    fontSize,
    color,
    align: "center",
    zIndex: 5,
    ...extra,
  }) as TemplateLayer;

function buildCanvaTemplate(spec: CanvaSpec): TemplatePreset {
  const radius = spec.borderRadius ?? 8;
  const slots: PhotoSlot[] = [];
  const layers: TemplateLayer[] = [];

  let width = 600;
  let height = 1800;
  let aspectRatio: AspectRatioPreset = "custom";
  let category: TemplateCategory = "photobox";

  const addFramedSlot = (
    id: string,
    index: number,
    x: number,
    y: number,
    w: number,
    h: number
  ) => {
    slots.push({
      id,
      index,
      x,
      y,
      width: w,
      height: h,
      borderRadius: radius,
      filter: spec.filter,
    });
    layers.push(
      makeRect(`frame-${id}`, x - 3, y - 3, w + 6, h + 6, "transparent", -1, {
        borderRadius: radius + 3,
        strokeColor: spec.borderColor,
        strokeWidth: 3,
      })
    );
  };

  if (spec.layout === "strip-3") {
    width = 600;
    height = 1800;
    [235, 650, 1065].forEach((y, i) => addFramedSlot(`slot-${i + 1}`, i, 68, y, 464, 386));
    layers.push(
      makeText("kicker", 40, 68, 520, 26, spec.kicker, spec.bodyFont, 15, spec.kickerColor, {
        letterSpacing: 3.5,
      }),
      makeText("title", 32, 104, 536, 72, spec.headline, spec.titleFont, 48, spec.titleColor),
      makeText("ft-title", 80, 1514, 440, 56, spec.footerTitle, spec.titleFont, 38, spec.titleColor),
      makeText("ft-sub", 60, 1582, 480, 26, spec.footerSub, spec.bodyFont, 13, spec.subColor, {
        letterSpacing: 2.2,
      })
    );
    if (spec.stickerTop) {
      layers.push(makeSticker("stk-top", spec.stickerTop, 456, 18, 108, 108, 10, 6));
    }
    if (spec.stickerLeft) {
      layers.push(makeSticker("stk-left", spec.stickerLeft, 24, 1500, 88, 88, -10, 6));
    }
    if (spec.stickerRight) {
      layers.push(makeSticker("stk-right", spec.stickerRight, 486, 1500, 88, 88, 12, 6));
    }
  } else if (spec.layout === "strip-4") {
    width = 600;
    height = 1800;
    [200, 542, 884, 1226].forEach((y, i) => addFramedSlot(`slot-${i + 1}`, i, 75, y, 450, 318));
    layers.push(
      makeText("kicker", 40, 52, 520, 24, spec.kicker, spec.bodyFont, 14, spec.kickerColor, {
        letterSpacing: 3,
      }),
      makeText("title", 32, 86, 536, 68, spec.headline, spec.titleFont, 44, spec.titleColor),
      makeText("ft-title", 80, 1582, 440, 48, spec.footerTitle, spec.titleFont, 34, spec.titleColor),
      makeText("ft-sub", 60, 1638, 480, 24, spec.footerSub, spec.bodyFont, 12, spec.subColor, {
        letterSpacing: 2,
      })
    );
    if (spec.stickerTop) {
      layers.push(makeSticker("stk-top", spec.stickerTop, 464, 14, 96, 96, 8, 6));
    }
    if (spec.stickerLeft) {
      layers.push(makeSticker("stk-left", spec.stickerLeft, 20, 1564, 80, 80, -12, 6));
    }
    if (spec.stickerRight) {
      layers.push(makeSticker("stk-right", spec.stickerRight, 500, 1564, 80, 80, 14, 6));
    }
  } else if (spec.layout === "dual-strip-3") {
    width = 800;
    height = 1200;
    aspectRatio = "2:3";
    [186, 472, 758].forEach((y, i) => {
      addFramedSlot(`slot-l-${i + 1}`, i, 38, y, 326, 266);
      addFramedSlot(`slot-r-${i + 1}`, i, 436, y, 326, 266);
    });
    // Center perforation divider
    for (let dy = 24; dy < 1170; dy += 26) {
      layers.push(makeRect(`dot-${dy}`, 398, dy, 4, 12, spec.borderColor, 4, { borderRadius: 2 }));
    }
    layers.push(
      makeText("kicker-l", 30, 52, 342, 22, spec.kicker, spec.bodyFont, 12, spec.kickerColor, {
        letterSpacing: 2.5,
      }),
      makeText("title-l", 26, 82, 350, 58, spec.headline, spec.titleFont, 34, spec.titleColor),
      makeText("kicker-r", 428, 52, 342, 22, spec.kicker, spec.bodyFont, 12, spec.kickerColor, {
        letterSpacing: 2.5,
      }),
      makeText("title-r", 424, 82, 350, 58, spec.headline, spec.titleFont, 34, spec.titleColor),
      makeText("ft-l", 30, 1054, 342, 40, spec.footerTitle, spec.titleFont, 26, spec.titleColor),
      makeText("ft-r", 428, 1054, 342, 40, spec.footerTitle, spec.titleFont, 26, spec.titleColor),
      makeText("sub-l", 30, 1102, 342, 22, spec.footerSub, spec.bodyFont, 11, spec.subColor, {
        letterSpacing: 1.8,
      }),
      makeText("sub-r", 428, 1102, 342, 22, spec.footerSub, spec.bodyFont, 11, spec.subColor, {
        letterSpacing: 1.8,
      })
    );
    if (spec.stickerLeft) {
      layers.push(makeSticker("stk-left", spec.stickerLeft, 24, 1036, 62, 62, -10, 6));
    }
    if (spec.stickerRight) {
      layers.push(makeSticker("stk-right", spec.stickerRight, 714, 1036, 62, 62, 12, 6));
    }
  } else if (spec.layout === "grid-2x2") {
    width = 800;
    height = 1200;
    aspectRatio = "2:3";
    category = "collage";
    const coords = [
      { x: 56, y: 190 },
      { x: 412, y: 190 },
      { x: 56, y: 608 },
      { x: 412, y: 608 },
    ];
    coords.forEach((c, i) => addFramedSlot(`slot-${i + 1}`, i, c.x, c.y, 332, 392));
    layers.push(
      makeText("kicker", 100, 48, 600, 24, spec.kicker, spec.bodyFont, 13, spec.kickerColor, {
        letterSpacing: 3,
      }),
      makeText("title", 90, 82, 620, 66, spec.headline, spec.titleFont, 46, spec.titleColor),
      makeText("ft-title", 120, 1038, 560, 46, spec.footerTitle, spec.titleFont, 34, spec.titleColor),
      makeText("ft-sub", 120, 1098, 560, 24, spec.footerSub, spec.bodyFont, 12, spec.subColor, {
        letterSpacing: 2.4,
      })
    );
    if (spec.stickerLeft) {
      layers.push(makeSticker("stk-left", spec.stickerLeft, 50, 68, 64, 64, -10, 6));
    }
    if (spec.stickerRight) {
      layers.push(makeSticker("stk-right", spec.stickerRight, 686, 68, 64, 64, 10, 6));
    }
  } else if (spec.layout === "hero-3") {
    width = 800;
    height = 1200;
    aspectRatio = "2:3";
    category = "collage";
    addFramedSlot("slot-1", 0, 56, 188, 688, 480);
    addFramedSlot("slot-2", 1, 56, 694, 332, 316);
    addFramedSlot("slot-3", 2, 412, 694, 332, 316);
    layers.push(
      makeText("kicker", 100, 48, 600, 24, spec.kicker, spec.bodyFont, 13, spec.kickerColor, {
        letterSpacing: 3,
      }),
      makeText("title", 90, 82, 620, 66, spec.headline, spec.titleFont, 46, spec.titleColor),
      makeText("ft-title", 120, 1040, 560, 46, spec.footerTitle, spec.titleFont, 34, spec.titleColor),
      makeText("ft-sub", 120, 1100, 560, 24, spec.footerSub, spec.bodyFont, 12, spec.subColor, {
        letterSpacing: 2.2,
      })
    );
    if (spec.stickerLeft) {
      layers.push(makeSticker("stk-left", spec.stickerLeft, 48, 1028, 68, 68, -12, 6));
    }
    if (spec.stickerRight) {
      layers.push(makeSticker("stk-right", spec.stickerRight, 684, 1028, 68, 68, 12, 6));
    }
  } else {
    // landscape-3 (1200x800 Canva 4x6 horizontal postcard photobooth)
    width = 1200;
    height = 800;
    aspectRatio = "custom";
    category = "collage";
    [60, 434, 808].forEach((x, i) => addFramedSlot(`slot-${i + 1}`, i, x, 196, 332, 430));
    layers.push(
      makeText("kicker", 180, 46, 840, 24, spec.kicker, spec.bodyFont, 14, spec.kickerColor, {
        letterSpacing: 3.5,
      }),
      makeText("title", 160, 80, 880, 70, spec.headline, spec.titleFont, 50, spec.titleColor),
      makeText("ft-title", 180, 656, 840, 46, spec.footerTitle, spec.titleFont, 34, spec.titleColor),
      makeText("ft-sub", 180, 712, 840, 24, spec.footerSub, spec.bodyFont, 12, spec.subColor, {
        letterSpacing: 2.5,
      })
    );
    if (spec.stickerLeft) {
      layers.push(makeSticker("stk-left", spec.stickerLeft, 56, 56, 78, 78, -10, 6));
    }
    if (spec.stickerRight) {
      layers.push(makeSticker("stk-right", spec.stickerRight, 1066, 56, 78, 78, 10, 6));
    }
  }

  return {
    id: spec.id,
    slug: spec.id,
    title_id: spec.title,
    title_en: spec.title,
    description_id: spec.descId,
    description_en: spec.descEn,
    category,
    theme: spec.theme,
    is_featured: (spec.popularity ?? 90) >= 92,
    is_new: true,
    popularity_score: spec.popularity ?? 90,
    document: {
      schemaVersion: "1.0",
      templateId: spec.id,
      version: 1,
      category,
      theme: spec.theme,
      canvas: {
        width,
        height,
        aspectRatio,
        background: {
          type: spec.isGradient ? "gradient" : "solid",
          value: spec.bg,
        },
      },
      slots,
      layers,
      watermark: enforceMandatoryWatermark({
        placement: spec.watermarkPlacement ?? "bottom-center",
        contrastMode: spec.contrastMode,
        fontFamily: spec.bodyFont,
        style: spec.watermarkStyle ?? "minimal",
      }),
    },
  };
}

