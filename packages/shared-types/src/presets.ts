/**
 * Generates a custom multi-shot photobox strip template for 2 to 8 shots.
 */
export function createDynamicPhotoboxTemplate(
  shotCount: number,
  options?: { dark?: boolean; caption?: string }
): TemplateDocument {
  const count = Math.max(2, Math.min(8, Math.round(shotCount)));
  const isDark = options?.dark ?? false;
  const cols = count <= 4 ? 1 : 2;
  const rows = Math.ceil(count / cols);
  const slotW = cols === 1 ? 504 : 360;
  const slotH = cols === 1 ? 300 : 280;
  const gap = 24;
  const padX = 48;
  const padTop = 56;
  const footerH = 170;

  const width = padX * 2 + cols * slotW + (cols - 1) * gap;
  const height = padTop + rows * slotH + (rows - 1) * gap + footerH;

  const slots = Array.from({ length: count }, (_, i) => {
    const col = i % cols;
    const row = Math.floor(i / cols);
    return {
      id: `slot-${i + 1}`,
      index: i,
      x: padX + col * (slotW + gap),
      y: padTop + row * (slotH + gap),
      width: slotW,
      height: slotH,
      borderRadius: 12,
      filter: "natural" as const,
    };
  });

  const footerY = padTop + rows * slotH + (rows - 1) * gap + 32;

  return {
    schemaVersion: "1.0",
    templateId: `custom-photobox-${count}`,
    version: 1,
    category: "photobox",
    theme: isDark ? "dark" : "minimal",
    canvas: {
      width,
      height,
      aspectRatio: "custom",
      background: { type: "solid", value: isDark ? "#1b1917" : "#faf8f5" },
    },
    slots,
    layers: [
      {
        id: "title-1",
        type: "text",
        zIndex: 10,
        x: padX,
        y: footerY,
        width: width - padX * 2,
        height: 40,
        visible: true,
        content: options?.caption ?? `PHOTOSTUDIO ${count}-CUT`,
        fontFamily: "Plus Jakarta Sans, system-ui, sans-serif",
        fontSize: 26,
        color: isDark ? "#f5f5f4" : "#1c1917",
        align: "center",
        letterSpacing: 3,
      },
      {
        id: "date-1",
        type: "date",
        zIndex: 11,
        x: padX,
        y: footerY + 48,
        width: width - padX * 2,
        height: 28,
        visible: true,
        content: "{{date}}",
        fontFamily: "Plus Jakarta Sans, system-ui, sans-serif",
        fontSize: 16,
        color: isDark ? "#a8a29e" : "#78716c",
        align: "center",
        letterSpacing: 2,
      },
    ],
    watermark: enforceMandatoryWatermark({
      placement: "bottom-right",
      contrastMode: isDark ? "light" : "dark",
    }),
  };
}
