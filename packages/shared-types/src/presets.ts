export const NEW_TEMPLATE_TTL_MS = 3 * 24 * 60 * 60 * 1000;

export interface TemplatePreset {
  id: string;
  slug: string;
  title_id: string;
  title_en: string;
  description_id: string;
  description_en: string;
  category: TemplateCategory;
  theme: TemplateTheme;
  popularity_score: number;
  is_featured: boolean;
  is_new: boolean;
  /** Optional ISO-8601 timestamp when this template was added/updated */
  added_at?: string;
  /** Optional ISO-8601 timestamp before which this template is locked */
  unlock_at?: string;
  document: TemplateDocument;
}

export function isTemplateLocked(
  preset: Pick<TemplatePreset, "unlock_at">,
  nowMs: number = Date.now()
): boolean {
  if (!preset.unlock_at) return false;
  const unlockMs = Date.parse(preset.unlock_at);
  if (!Number.isFinite(unlockMs)) return false;
  return nowMs < unlockMs;
}

export function getTemplateAddedTimestamp(preset: Pick<TemplatePreset, "added_at">): number {
  if (!preset.added_at) return 0;
  const ts = Date.parse(preset.added_at);
  return Number.isFinite(ts) ? ts : 0;
}

export function isTemplateNew(
  preset: Pick<TemplatePreset, "is_new" | "added_at">,
  nowMs: number = Date.now()
): boolean {
  if (!preset.is_new) return false;
  const addedMs = getTemplateAddedTimestamp(preset);
  if (addedMs <= 0) return false;
  return nowMs - addedMs < NEW_TEMPLATE_TTL_MS;
}

